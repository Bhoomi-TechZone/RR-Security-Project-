export function getStoredHubRequests() {
  try {
    const raw = localStorage.getItem(HUB_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch {
    // fallback to initial
  }
  return INITIAL_HUB_REQUESTS;
}

export function saveStoredHubRequests(list) {
  try {
    localStorage.setItem(HUB_STORAGE_KEY, JSON.stringify(list));
  } catch {
    // ignore storage quota errors
  }
}

export function addHubRequest(newReq) {
  const current = getStoredHubRequests();
  const next = [newReq, ...current];
  saveStoredHubRequests(next);
  return next;
}

export function updateHubRequestStatus(id, status, remarks = '') {
  const current = getStoredHubRequests();
  const next = current.map((item) =>
    item.id === id
      ? {
          ...item,
          status,
          remarks: remarks || item.remarks,
          stage:
            status === 'Approved'
              ? 'Approved by HR / Admin'
              : status === 'Rejected'
              ? 'Rejected by HR / Admin'
              : status === 'Cancelled'
              ? 'Withdrawn by Employee'
              : item.stage,
        }
      : item
  );
  saveStoredHubRequests(next);
  return next;
}
